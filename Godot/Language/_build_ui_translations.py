def _godot_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_tres(filename: str, locale: str, col: int, uid: str) -> None:
    lines = [
        f'[gd_resource type="Translation" format=3 uid="{uid}"]',
        "",
        "[resource]",
        f'locale = "{locale}"',
        "messages = {",
    ]
    for key in sorted(T.keys()):
        trs = T[key][col]
        lines.append(f'"{_godot_escape(key)}": "{_godot_escape(trs)}",')
    lines.append("}")
    path = ROOT / filename
    path.write_text("\n".join(lines), encoding="utf-8")
    print(path, len(T))


